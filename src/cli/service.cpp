ServiceKind host_service_kind() {
#if defined(_WIN32)
	return ServiceKind::TaskScheduler;
#elif defined(__APPLE__)
	return ServiceKind::Launchd;
#else
	return ServiceKind::Systemd;
#endif
}

bool parse_service_kind(const std::string &text, ServiceKind &out) {
	if (text == "systemd")
		out = ServiceKind::Systemd;
	else if (text == "launchd")
		out = ServiceKind::Launchd;
	else if (text == "task")
		out = ServiceKind::TaskScheduler;
	else
		return false;
	return true;
}

std::string render_service(ServiceKind kind, const ServiceSpec &spec) {
	switch (kind) {
		case ServiceKind::Systemd:
			return systemd_unit(spec);
		case ServiceKind::Launchd:
			return launchd_plist(spec);
		case ServiceKind::TaskScheduler:
			return task_xml(spec);
	}
	return {};
}

std::string service_file_name(ServiceKind kind, const std::string &name) {
	switch (kind) {
		case ServiceKind::Systemd:
			return "voxel-browser-" + name + ".service";
		case ServiceKind::Launchd:
			return label(name) + ".plist";
		case ServiceKind::TaskScheduler:
			return "voxel-browser-" + name + ".xml";
	}
	return {};
}

std::string service_install_hint(ServiceKind kind, const ServiceSpec &spec) {
	const std::string file = service_file_name(kind, spec.name);
	switch (kind) {
		case ServiceKind::Systemd:
			return "To run '" + spec.name + "' as a user service (no root needed):\n"
											"  mkdir -p ~/.config/systemd/user\n"
											"  vb server service print " +
					spec.name + " > ~/.config/systemd/user/" + file + "\n"
																	  "  systemctl --user daemon-reload && systemctl --user enable --now " +
					file + "\n"
						   "To keep it running when you are logged out:  loginctl enable-linger $USER\n"
						   "Remove:  systemctl --user disable --now " +
					file + " && rm ~/.config/systemd/user/" + file + "\n";
		case ServiceKind::Launchd:
			return "To run '" + spec.name + "' as a login agent:\n"
											"  vb server service print " +
					spec.name + " > ~/Library/LaunchAgents/" + file + "\n"
																	  "  launchctl bootstrap gui/$(id -u) ~/Library/LaunchAgents/" +
					file + "\n"
						   "Remove:  launchctl bootout gui/$(id -u)/" +
					label(spec.name) + " && rm ~/Library/LaunchAgents/" + file + "\n";
		case ServiceKind::TaskScheduler:
			return "To run '" + spec.name + "' as a task at logon (PowerShell, no administrator needed):\n"
											"  vb server service print " +
					spec.name + " | Out-File -Encoding Unicode " + file + "\n"
																		  "  schtasks /Create /TN \"VoxelBrowser\\" +
					spec.name + "\" /XML " + file + "\n"
													"  schtasks /Run /TN \"VoxelBrowser\\" +
					spec.name + "\"\n"
								"Stop it with `vb server stop " +
					spec.name + "` (ending the task from Task Scheduler\n"
								"terminates the server without saving the world).\n"
								"Remove:  schtasks /Delete /TN \"VoxelBrowser\\" +
					spec.name + "\" /F\n";
	}
	return {};
}

